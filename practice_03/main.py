"""
Задача:
Отбирает только положительные числа.
Среди них оставляет числа, которые делятся на 3 или 5.
Возводит каждое подходящее число в квадрат.
"""

nums = (12, -7, 25, 30, -15, 8, 42, 19, -20, 33)

g = (num**2 for num in nums if num > 0 and (num % 3 == 0 or num % 5 == 0))
print(list(g))
